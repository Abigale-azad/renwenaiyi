assert.equal(growth.ensurePersonalityGrowthWorldBooks([{id:'a'}]).length,1);
for (const id of ['builtin_phone_lookup_wechat_contacts','builtin_phone_lookup_wechat_messages','builtin_phone_lookup_chat_history','builtin_phone_lookup_people_brief']) assert.equal(policy.isPrivateChatLookup(id),true);
