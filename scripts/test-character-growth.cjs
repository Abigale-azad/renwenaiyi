// Node-only regression tests; uses an isolated in-memory KV, never user data.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const kv = new Map();
function load(file, dependencies = {}) {
  const js = ts.transpileModule(fs.readFileSync(path.join(root, file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const exports = {};
  vm.runInNewContext(js, { exports, require: name => { if (!(name in dependencies)) throw new Error(name); return dependencies[name]; }, crypto: { randomUUID }, Date, Set, console });
  return exports;
}
const storage = load('lib/character-growth-storage.ts', { './kv-db': { kvGet: k => kv.get(k), kvSet: (k,v) => kv.set(k,v), registerKvMigration() {} } });
const policy = load('lib/character-privacy-policy.ts');
assert.equal(storage.mayReadOtherChats(), false);
assert.equal(storage.mayReadOtherChats('a'), false);
storage.setOtherChatsPermission('a', true);
assert.equal(storage.mayReadOtherChats('a'), true);
assert.equal(storage.mayReadOtherChats('b'), false);
storage.setOtherChatsPermission('a', false);
assert.equal(storage.mayReadOtherChats('a'), false);
storage.addGrowthCandidate('a', { id:'one', content:'A-only', createdAt:1, source:'test', evidence:'own interaction' });
storage.addGrowthCandidate('a', { id:'one', content:'duplicate', createdAt:1, source:'test', evidence:'' });
assert.equal(storage.loadCharacterGrowth('a').revisions.length, 1);
assert.equal(storage.approvedGrowthText('a'), '');
storage.decideGrowth('a','one',true,'edited A');
assert.equal(storage.approvedGrowthText('a'), 'edited A');
assert.equal(storage.approvedGrowthText('b'), '');
storage.decideGrowth('a','one',true);
assert.equal(storage.approvedGrowthText('a'), 'A-only');
assert.equal(storage.loadCharacterGrowth('a').revisions.filter(r=>r.status==='approved').length, 1);
assert.ok(storage.loadCharacterGrowth('a').revisions.some(r=>r.content==='edited A'));
const active = storage.loadCharacterGrowth('a').revisions.find(r=>r.status==='approved');
storage.decideGrowth('a',active.id,false);
assert.equal(storage.approvedGrowthText('a'), '');
const books = [{ id:'old', name:'A', description:'auto-personality-growth:a', updatedAt:1, entries:[{uid:'entry',content:'old A',comment:'current'}] }, {id:'normal',description:'world',entries:[]}];
const snapshot = JSON.stringify(books);
